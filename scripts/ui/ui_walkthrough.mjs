// Drives the real UI in jsdom against a running server (http://localhost:8765). Setup: cd scripts/ui && npm i jsdom
import { JSDOM } from 'jsdom';
const base = 'http://localhost:8765';
const html = await (await fetch(base + '/')).text();
const errors = [];
const dom = new JSDOM(html, { runScripts: 'dangerously', url: base + '/', pretendToBeVisual: true, beforeParse(w) {
  w.fetch = (u, o) => fetch(new URL(u, base), o);
  w.FormData = globalThis.FormData; w.File = globalThis.File; w.Blob = globalThis.Blob;
  w.addEventListener('error', e => errors.push(String(e.error || e.message)));
  w.URL.createObjectURL = () => 'blob:x';
}});
const w = dom.window, d = w.document;
const sleep = ms => new Promise(r => setTimeout(r, ms));
const until = async (f, ms = 60000) => { const t = Date.now(); while (Date.now() - t < ms) { if (f()) return true; await sleep(200); } console.log('TOASTS', [...d.body.children].filter(e=>e.style.position==='fixed').map(e=>e.textContent)); throw new Error('timeout: ' + f); };
const txt = () => d.body.textContent;
await until(() => d.querySelector('#li'));
d.querySelector('#em').value = 'ui@example.com'; d.querySelector('#pw').value = 'password123';
d.querySelector('#rg').click();
await until(() => d.querySelector('#demo'));
console.log('1 registered, shell rendered');
d.querySelector('#demo').click();
await until(() => d.querySelector('#gen'));
console.log('2 demo loaded; before score shown:', /before/.test(txt()));
d.querySelector('#gen').click();
await until(() => d.querySelector('#exe'));
console.log('3 plan rows:', d.querySelectorAll('[data-s]').length);
d.querySelector('[data-pv]').click();
await until(() => [...d.querySelectorAll('tr[id^=pv-]')].some(r => !r.hidden && r.textContent.length > 20));
console.log('4 step preview rendered');
d.querySelector('#exe').click();
await until(() => d.querySelector('#after') && d.querySelector('#after').textContent.includes('Result'));
console.log('5 applied:', d.querySelector('#after .gauges').textContent.replace(/\s+/g, ' ').trim());
console.log('   versions buttons:', d.querySelectorAll('[data-rv]').length, '| downloads:', d.querySelectorAll('[data-dl]').length);
d.querySelector('[data-rc=python]').click();
await until(() => !d.querySelector('#rcv').hidden && d.querySelector('#rcv').textContent.length > 100);
console.log('6 python recipe shown');
const tab = k => d.querySelector(`.tabs button[data-t=${k}]`).click();
tab('risks'); await until(() => /Risk grid/.test(txt())); console.log('7 risks tab ok');
tab('ask'); d.querySelector('#q').value = 'average amount_inr by city'; d.querySelector('#go').click();
await until(() => d.querySelector('#ans pre')); console.log('8 ask ok:', d.querySelector('#ans h3').textContent.slice(0, 40), '| chart svg:', !!d.querySelector('#ans svg'));
tab('forecast'); d.querySelector('#go').click(); await until(() => d.querySelector('#fo svg')); console.log('9 forecast chart ok');
tab('strategy'); await until(() => /CEO brief/.test(txt()) && d.querySelector('#sim')); console.log('10 strategy ok:', d.querySelectorAll('[data-o]').length, 'assumption inputs');
d.querySelector('#sim').click(); await sleep(1500);
tab('crew'); d.querySelector('#cr').click(); await until(() => d.querySelector('#ap')); console.log('11 crew paused at approval gate');
d.querySelector('#ap').click(); await until(() => /Strategist/.test(d.querySelector('#run').textContent)); console.log('12 crew finished');
tab('trust'); await until(() => d.querySelector('#pp')); d.querySelector('#pp').click(); await until(() => d.querySelector('#pr a'));
const href = d.querySelector('#pr a').getAttribute('href'); console.log('13 passport issued:', href.slice(0, 20));
const pp = new JSDOM(await (await fetch(base + href)).text(), { runScripts: 'dangerously', url: base + href, beforeParse(x) { x.fetch = (u, o) => fetch(new URL(u, base), o); } });
await until(() => pp.window.document.querySelector('#v')); pp.window.document.querySelector('#v').click();
await until(() => /verified/.test(pp.window.document.querySelector('#vr').textContent)); console.log('14 passport page verify:', pp.window.document.querySelector('#vr').textContent);
tab('data'); await until(() => /Profile/.test(txt())); console.log('15 data tab ok');
console.log('JS errors:', errors.length ? errors : 'none');
process.exit(0);
